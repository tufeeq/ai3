const assert=require('assert');
const P=require('../predictive-radar.js');
const observedAt='2026-08-31T01:00:00.000Z';
const base={symbol:'TEST',price:10,changePct:2,observedAt,movementIndex:72,ignitionIndex:68,continuationIndex:70,distributionRisk:22,riskScore:30,lifecycle:'ARMED',stage:'PRE_IGNITION',dataConfidence:{fresh:true,score:90},sharia:{status:'VERIFIED'},whyNow:['تراكم سيولة','تسارع حجم التداول'],invalidation:'structure failure'};
const p=P.build(base,'2026-08-31T01:01:00Z');
assert.equal(p.status,'EXPERIMENTAL');
assert.equal(p.calibration,'UNCALIBRATED');
assert.equal(p.probability,null,'must not invent probability before calibration');
assert.equal(p.direction,'UPSIDE');
assert.ok(p.expectedMoveRangePct.maxPct>p.expectedMoveRangePct.minPct);
assert.equal(p.evidenceCutoff,observedAt);
assert.ok(Date.parse(p.generatedAt)>=Date.parse(p.evidenceCutoff),'prediction timestamp must not precede evidence cutoff');
assert.equal(P.build({...base,observedAt:null},'2026-08-31T01:01:00Z').blockedReason,'MISSING_EVIDENCE_CUTOFF');
assert.equal(P.build(base,'2026-08-31T00:59:59Z').blockedReason,'PREDICTION_BEFORE_EVIDENCE_CUTOFF');
assert.equal(P.build({...base,sharia:{status:'NON_COMPLIANT'}},'2026-08-31T01:01:00Z').blockedReason,'SHARIA_NON_COMPLIANT');
assert.equal(P.build({...base,sharia:{status:'CONFLICT_REVIEW'}},'2026-08-31T01:01:00Z').blockedReason,'SHARIA_CONFLICT_REVIEW');
assert.equal(P.build({...base,dataConfidence:{fresh:false,score:90}},'2026-08-31T01:01:00Z').blockedReason,'DATA_NOT_FRESH_ENOUGH');
const mem=new Map();const storage={getItem:k=>mem.get(k)||null,setItem:(k,v)=>mem.set(k,v)};
P.persist([p],storage);P.persist([{...p,evidenceScore:1}],storage);
assert.equal(JSON.parse(mem.get(P.KEY))[0].evidenceScore,p.evidenceScore,'frozen prediction must not be overwritten');
console.log('predictive-radar-contract: ok');
