const fs=require('fs');
const vm=require('vm');
const assert=require('assert');
const src=fs.readFileSync('app.js','utf8');
const m=src.match(/function rowsOf\(p\)\{[^\n]+\}/);
assert(m,'rowsOf helper must exist in app.js');
const ctx={};
vm.createContext(ctx);
vm.runInContext(`${m[0]};this.rowsOf=rowsOf;`,ctx);
const keyed={quotes:{HYFM:{ticker:'HYFM',price:1.05,timestampET:'2026-09-01T13:21:00-04:00'},SOAR:{price:0.25,timestampET:'2026-09-01T13:21:49-04:00'}}};
const rows=ctx.rowsOf(keyed);
assert.strictEqual(rows.length,2,'keyed live quote map must become two rows');
const hyfm=rows.find(x=>x.symbol==='HYFM');
const soar=rows.find(x=>x.symbol==='SOAR');
assert(hyfm&&hyfm.price===1.05,'existing ticker must be preserved as symbol');
assert(soar&&soar.price===0.25,'map key must backfill missing symbol/ticker');
const arr=[{ticker:'ABC',price:1}];
assert.strictEqual(ctx.rowsOf({quotes:arr}),arr,'array payload behavior must remain unchanged');
assert.deepStrictEqual(Array.from(ctx.rowsOf({quotes:null})),[],'missing quote rows must fail closed');
console.log('live-quote-map-contract: ok');
